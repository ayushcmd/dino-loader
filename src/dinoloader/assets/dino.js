/**
 * Returns a composite SVG containing all dinosaur poses as grouped layers.
 * Uses exact viewBox="0 0 24 23" so feet rest flush with the bottom edge.
 */
export function createDinoSvg() {
  const f1 = gridToGroup(DINO_RUN_1, { className: 'dl-dino-f dl-dino-run-1' });
  const f2 = gridToGroup(DINO_RUN_2, { className: 'dl-dino-f dl-dino-run-2' });
  const fj = gridToGroup(DINO_JUMP, { className: 'dl-dino-f dl-dino-jump' });
  const fc = gridToGroup(DINO_CRASH, { className: 'dl-dino-f dl-dino-crash' });
  const fw = gridToGroup(DINO_WIN, { className: 'dl-dino-f dl-dino-win' });

  return `
    <svg xmlns="http://www.w3.org/2000/svg"
         viewBox="0 0 24 23"
         shape-rendering="crispEdges"
         class="dl-dino-svg"
         fill="currentColor"
         aria-label="Pixel art dinosaur">
      <g class="dl-dino-run-group">
        ${f1}
        ${f2}
      </g>
      ${fj}
      ${fc}
      ${fw}
    </svg>
  `.trim();
}
